import 'server-only';
import { v2 as cloudinary, type UploadApiResponse } from 'cloudinary';
import { env } from '@/lib/env';

cloudinary.config({
  cloud_name: env.CLOUDINARY_CLOUD_NAME,
  api_key: env.CLOUDINARY_API_KEY,
  api_secret: env.CLOUDINARY_API_SECRET,
  secure: true,
});

// Vercel functions accept request bodies up to 4.5 MB, so uploads through the server are capped at 4 MB.
export const MAX_DOCUMENT_BYTES = 4 * 1024 * 1024;
export const MAX_AVATAR_BYTES = 2 * 1024 * 1024;

/** Allowed document types, identified by their file signature ("magic bytes"), not by the browser-supplied MIME type. */
const SIGNATURES: { mime: string; ext: string; test: (b: Buffer) => boolean }[] = [
  { mime: 'application/pdf', ext: 'pdf', test: (b) => b.subarray(0, 5).toString('latin1') === '%PDF-' },
  { mime: 'image/png', ext: 'png', test: (b) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) },
  { mime: 'image/jpeg', ext: 'jpg', test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  {
    mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    ext: 'docx',
    test: (b) => b.subarray(0, 4).equals(Buffer.from([0x50, 0x4b, 0x03, 0x04])) && b.includes(Buffer.from('word/')),
  },
  { mime: 'application/msword', ext: 'doc', test: (b) => b.subarray(0, 8).equals(Buffer.from([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1])) },
];

export function detectDocumentType(buffer: Buffer) {
  return SIGNATURES.find((s) => s.test(buffer)) ?? null;
}

export function detectImageType(buffer: Buffer) {
  const t = detectDocumentType(buffer);
  return t && t.mime.startsWith('image/') ? t : null;
}

function uploadBuffer(buffer: Buffer, options: Record<string, unknown>): Promise<UploadApiResponse> {
  return new Promise((resolve, reject) => {
    cloudinary.uploader
      .upload_stream(options, (error, result) => {
        if (error || !result) reject(error ?? new Error('Upload failed'));
        else resolve(result);
      })
      .end(buffer);
  });
}

/**
 * Stores a case document as a private ("authenticated") raw asset.
 * It cannot be fetched without a signed URL generated by this server.
 */
export async function uploadCaseDocument(buffer: Buffer, caseId: string, ext: string) {
  const result = await uploadBuffer(buffer, {
    resource_type: 'raw',
    type: 'authenticated',
    folder: `courtcaseflow/cases/${caseId}`,
    // Random name (no user-supplied filename in the storage path).
    public_id: `${crypto.randomUUID()}.${ext}`,
    overwrite: false,
  });
  return { storageKey: result.public_id, bytes: result.bytes };
}

/** Short-lived (5 minute) signed download link. Only call after checking the user may see the document. */
export function signedDocumentUrl(storageKey: string) {
  return cloudinary.utils.private_download_url(storageKey, '', {
    resource_type: 'raw',
    type: 'authenticated',
    expires_at: Math.floor(Date.now() / 1000) + 300,
    attachment: true,
  });
}

export async function deleteCaseDocument(storageKey: string) {
  await cloudinary.uploader.destroy(storageKey, { resource_type: 'raw', type: 'authenticated', invalidate: true });
}

/** Profile pictures are public, resized to 256x256, and stored under the user's id. */
export async function uploadAvatar(buffer: Buffer, userId: string) {
  const result = await uploadBuffer(buffer, {
    resource_type: 'image',
    type: 'upload',
    folder: 'courtcaseflow/avatars',
    public_id: userId,
    overwrite: true,
    invalidate: true,
    transformation: [{ width: 256, height: 256, crop: 'fill', gravity: 'face', fetch_format: 'auto', quality: 'auto' }],
  });
  // Cache-bust so the new picture shows straight away.
  return `${result.secure_url}?v=${result.version}`;
}
